import os
import sys

ListName = None

def ListSelector():
    Lists = []
    for file in os.listdir():
        if file.endswith(".txt"):
            Lists.append(file)
    if not Lists:
        print("No todo lists found. Creating a new one...")
        ListName = input("Please enter the name of the new todo list (without the .txt extension): ")
        ListName += ".txt"
        with open(ListName, "w") as ListFile:
            ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
            return ListName
    else:
        Lists.insert(0, "Delete List")
        Lists.insert(1, "New List")
        while True:
            print("Please select a todo list:")
            for i, list_name in enumerate(Lists, 0):
                print(f"{i}. {list_name}")
            try:
                choice = int(input("Please enter the number of the todo list you would like to use: "))
                if 0 <= choice <= len(Lists) - 1 :
                    if Lists[choice] == "New List":
                        ListName = input("Please enter the name of the new todo list (without the .txt extension): ")
                        ListName += ".txt"
                        with open(ListName, "w") as ListFile:
                            ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
                            return ListName
                    elif Lists[choice] == "Delete List":
                        Lists.remove("Delete List")
                        Lists.remove("New List")
                        print("Please select a todo list to delete:")
                        for i, list_name in enumerate(Lists, 1):
                            print(f"{i}. {list_name}")
                        choice = input("Please type the number of the todo list to delete:")
                        try:
                                choice = int(choice)
                        except:
                                print("Please enter a valid input.")
                                input("Press enter to continue...")
                        if 1 <= choice <= len(Lists):
                            choice = Lists[choice - 1]
                        else:
                            print("Please enter a valid value.")
                            continue
                        Confirmation = input(f"Are you 100% sure you would like to delete {choice}? Please enter the name of the list EXACTLY including the .txt extension to continue or type cancel: ")
                        if Confirmation == choice:
                            os.remove(choice)
                            print(f"Successfully deleted {choice}.")
                            continue
                    else:
                        return Lists[choice]
                else:
                    print("Invalid input. Please enter a valid list number.")
            except ValueError:
                print("Invalid input. Please enter a valid list number.")

def Initilization():
    global ListName
    ListName = ListSelector()
    if os.path.exists(ListName):
        with open(ListName, "r") as ListFile:
            if ListFile.readline() != f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n":
                print(f"The {ListName} file is corrupted. Would you like to delete it and create a new one? (Y/N)")
                choice = input().lower()
                if choice in [ "y", "yes"]:
                    os.remove(ListName)
                    with open(ListName, "w") as ListFile:
                        ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
                else:
                    print("Exiting...")
                    sys.exit(0)
    else:
        print(f"The {ListName} file does not exist. Creating it now...")
        with open(ListName, "w") as ListFile:
            ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")

def CheckList():
    global ListName
    if os.path.exists(ListName):
        with open(ListName, "r") as ListFile:
            if not os.path.exists(ListName) or ListFile.readline() != f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n":
                input(f"The {ListName} is corrupted. Please do not modify or delete the file, especially while the application is running. Press Enter to continue...")
                input(f"The {ListName} will now be reset. Press Enter to continue or close the application to cancel...")
                if os.path.exists(ListName):
                    os.remove(ListName)
                with open(ListName, "w") as ListFile:
                    ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
    else:
        input(f"The {ListName} does not exist. Please do not modify or delete the file, especially while the application is running. Press Enter to continue...")
        input(f"The {ListName} will now be created. Press Enter to continue or close the application to cancel...")
        with open(ListName, "w") as ListFile:
            ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")

def StartTodoList():
    global ListName
    TodoListRunning = True
    Initilization()
    while TodoListRunning:
        print('''
Please select the operation you would like to perform:

1. Read List
2. Add Task
3. Remove Task
4. Different List
5. Exit
''')
        print(f"Current todo list: {ListName}")
        Operation = input("Please enter the number for the operation you would like to perform: ")
        try:
            Operation = int(Operation)
        except ValueError:
            print("Invalid input. Please enter a valid operation number.")
            input("Press Enter to continue...")
            continue
        match Operation:
            case 1:
                # Read List
                CheckList()
                with open(ListName, "r") as ListFile:
                    Tasks = []
                    for line in ListFile:
                        if line != f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n" and line != "\n":
                            Tasks.append(line.strip())
                    if not Tasks:
                        print("The todo list is empty.")
                        input("Press Enter to continue...")
                    else:
                        print("The tasks in the todo list are: \n")
                        for task in Tasks:
                            print(task)
                        input("\n Press Enter to continue...")
            case 2:
                CheckList()
                Lines = []
                Task = input("Please enter the task you would like to add: ")
                if Task == "":
                    print("You cannot add an empty task. Please enter a valid task.")
                    input("Press Enter to continue...")
                    continue
                elif Task == f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n":
                    print("You cannot add this task as it is reserved for the application. Please enter a different task.")
                    input("Press Enter to continue...")
                    continue
                elif Task == "\n":
                    print("You cannot add a task that is just a newline. Please enter a different task.")
                    input("Press Enter to continue...")
                    continue
                elif Task == "Cancel":
                    print("You cannot add a task with the name 'Cancel' as it is reserved for the application. Please enter a different task.")
                    input("Press Enter to continue...")
                    continue
                with open(ListName, "r") as ListFile:
                    for line in ListFile:
                        if line != f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n" and line != "\n":
                            Lines.append(line)
                            if line == Task + "\n":
                                print("This task already exists in the todo list. Please enter a different task.")
                                input("Press Enter to continue...")
                                continue
                    if not Lines:
                        print("The todo list is empty. This task will be added as the first task.")
                        with open(ListName, "a") as ListFile:
                            ListFile.write(Task + "\n")
                        print(f"Task '{Task}' has been added to the todo list.")
                        input("Press Enter to continue...")
                        continue
                    else:
                        for i, line in enumerate(Lines):
                            print(f"{i + 1}. {line.strip()}")
                        TaskNumber = input("\nPlease enter the number of the task you would like to add this task after: ")
                        try:
                            TaskNumber = int(TaskNumber)
                            if TaskNumber < 1 or TaskNumber > len(Lines):
                                print("Invalid task number. Please enter a valid task number.")
                                input("Press Enter to continue...")
                                continue
                            Lines.insert(TaskNumber, Task + "\n")
                            with open(ListName, "w") as ListFile:
                                ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
                                for line in Lines:
                                    ListFile.write(line)
                            print(f"Task '{Task}' has been added to the todo list.")
                            input("Press Enter to continue...")
                        except ValueError:
                            print("Invalid input. Please enter a valid task number.")
                            input("Press Enter to continue...")
            case 3:
                CheckList()
                with open(ListName, "r") as ListFile:
                    Lines    = []
                    for line in ListFile:
                        if line != f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n" and line != "\n":
                            Lines.append(line.strip())
                    if not Lines:
                        print("The todo list is empty. There are no tasks to remove.")
                        input("Press Enter to continue...")
                    else:
                        Lines.insert(0, "Cancel")
                        print("The tasks in the todo list are: \n")
                        for i, task in enumerate(Lines):
                            print(f"{i + 1}. {task}")
                        TaskNumber = input("\nPlease enter the number of the task you would like to remove: ")
                        try:
                            TaskNumber = int(TaskNumber)
                            if TaskNumber < 1 or TaskNumber > len(Lines):
                                print("Invalid task number. Please enter a valid task number.")
                                input("Press Enter to continue...")
                                continue
                            TaskToRemove = Lines[TaskNumber - 1]
                            if TaskToRemove == "Cancel":
                                print("Task removal cancelled.")
                                input("Press Enter to continue...")
                                continue
                            Lines.remove(TaskToRemove)
                            with open(ListName, "w") as ListFile:
                                ListFile.write(f"This file is for use with the Todo List application in CoolUtilities.py. Please do not edit this file manually, as it may cause issues with the application.\n")
                                for task in Lines:
                                    ListFile.write(task + "\n")
                            print(f"Task '{TaskToRemove}' has been removed from the todo list.")
                            input("Press Enter to continue...")
                        except ValueError:
                            print("Invalid input. Please enter a valid task number.")
                            input("Press Enter to continue...")
            case 4:
                ListName = ListSelector()
            case 5:
                TodoListRunning = False
                break
            case _:
                print("Invalid input. Please enter a valid operation number.")
                input("Press Enter to continue...")
        
        

if __name__ == "__main__":
    StartTodoList()